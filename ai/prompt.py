import datetime

import ollama
import yaml


def generate_astrology_humor(birth_data, planets, houses, manifestation):
    """Генерирует юмористическую интерпретацию натальной карты"""

    # System prompt - строка с инструкциями
    system_prompt = """Ты — offline-LLM, которая генерирует креативные и юмористические интерпретации натальной карты.
Ты отвечаешь ТОЛЬКО на русском языке, всегда обращаясь ко второму лицу.
Твой стиль — дружелюбный, слегка игривый, без токсичности, с лёгким количеством шуток.

ВАЖНОЕ ПРАВИЛО: Используй ТОЛЬКО те данные, которые я тебе предоставлю. 
НЕ придумывай свои данные о положении планет, знаках зодиака или домах.
Если какого-то параметра нет в моих данных - просто не упоминай его. 
Должны быть проанализированы все 12 домов.

Формат речи:
  - Обращайся к пользователю как к собеседнику: "ты", "тебе", "твой".
  - Избегай официального тона.
  - Включай шуточки, например:
      * "Ну ты даёшь! С таким Марсом в Овне ты будто просыпаешься уже в режиме 'побеждать'".
      * "Луна в Рыбах? Ну всё, готовься плакать даже над рекламой зефира."
      * "С твоим Меркурием в Близнецах мыслей больше, чем вкладок в браузере."

Контекст:
  Пользователь передаёт положения планет и дополнительные данные рождения.
  Твоя задача — составить целостное, атмосферное описание личности, как будто ты астролог с чувством юмора.

Требования:
  - Не использовать научную терминологию.
  - Делать выводы цельными и художественными.
  - Не давать медицинских или юридических советов.
  - Не давать предсказаний, влияющих на жизнь (только характер, тенденции, стиль мышления).
  - Провести подробный анализ по каждому из домов и значений.
  - Указать на ключевые качества и недостатки.
  - Добавляй примеры реальных людей в описание домов.
  - Описание дома должно быть минимум 5-6 предложений.
  - Предположить кармическую задачу на эту жизнь.
  - Предположить прошлую жизнь.
  - Последнее предложения должны быть закончиными, без вопросительных знаков.
  - ПРИМЕР заголовка каждого дома: **Дом 1: Работа**"""

    # User prompt - тоже строка, но с данными внутри
    user_prompt = f"""
ДАННЫЕ ДЛЯ ИНТЕРПРЕТАЦИИ:

📅 Дата рождения: {birth_data.get('date')}
⏰ Время рождения: {birth_data.get('time')}
📍 Место рождения: {birth_data.get('place')}

🪐 ПОЛОЖЕНИЯ ПЛАНЕТ:
{chr(10).join([f"{planet}: {deg}" for planet, deg in planets.items()])}

🏠 ДОМА:
{chr(10).join([f"{house}: {deg}" for house, deg in houses.items()])}

📊 КЛЮЧЕВЫЕ ТОЧКИ:
Асцендент: {manifestation.get('ascendant')}
MC (Середина Неба): {manifestation.get('midheaven')}

---

Задача: Выдай цельное, образное и шуточное описание психологических особенностей пользователя,
основываясь на данных выше. Пиши так, будто рассказываешь другу про него самого.

Начни с краткого представления полученных данных, затем переходи к юмористической интерпретации.
Ставь разделители между каждым домом и аспектом.
"""

    messages = [
        {
            "role": "system",  # ОБЯЗАТЕЛЬНОЕ поле
            "content": system_prompt  # ОБЯЗАТЕЛЬНО строка
        },
        {
            "role": "user",  # ОБЯЗАТЕЛЬНОЕ поле
            "content": user_prompt  # ОБЯЗАТЕЛЬНО строка
        }
    ]

    try:
        response = ollama.chat(
            model="llama3.1:8b",  # или другая модель
            messages=messages,
            stream=True
        )

        print("\n" + "✨" * 30)
        print("ЮМОРИСТИЧЕСКИЙ АНАЛИЗ НАТАЛЬНОЙ КАРТЫ")
        print("✨" * 30 + "\n")

        full_response = ""
        for chunk in response:
            if 'message' in chunk and 'content' in chunk['message']:
                content = chunk['message']['content']
                print(content, end='', flush=True)
                full_response += content

        print("\n" + "✨" * 30)
        print("АНАЛИЗ ЗАВЕРШЕН! 🌟")
        print("✨" * 30)

        return full_response

    except Exception as e:
        print(f"Ошибка: {e}")
        return None

def start_generate():
    with open('../yaml/config_Penza_1481996_1530.yaml', 'r', encoding="utf-8") as f:
        templates = yaml.safe_load(f)


    # Данные из вашего примера
    birth_data = templates['content']['birth_data']

    planets = templates['content']['planets']

    houses = templates['content']['houses']

    manifestation = templates['content']['manifestation']

    text_cont =  generate_astrology_humor(birth_data, planets, houses, manifestation)
    with open(f"text.txt", "w", encoding="utf-8") as f:
        f.write(text_cont)
